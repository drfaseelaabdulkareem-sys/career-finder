// ============================================================
// CALIBRATION
//
// Each role's raw fit score has its own natural range — some roles
// score high for almost everybody, others score low for almost
// everybody. Ranking raw scores therefore makes a few roles dominate
// and buries the rest.
//
// This measures each role's own distribution across many simulated
// respondents, so the engine can ask "is this role unusually high
// FOR THIS ROLE?" rather than "is this number big?".
//
// Run after changing any weights or questions:
//   node scripts/calibrate.mjs
// ============================================================
import { writeFileSync } from 'node:fs';
import { QUESTIONS } from '../netlify/lib/questions.mjs';
import { ROLES } from '../netlify/lib/roles.mjs';
import { flattenAnswers, calculateDimensions } from '../netlify/lib/scoring.mjs';

const N = 40000;

function randomAnswers() {
  const a = {};
  for (const q of QUESTIONS) {
    if (q.type === 'multi-select') {
      const max = q.maxSelections || 10;
      const n = 1 + Math.floor(Math.random() * Math.min(max, q.options.length));
      a[q.id] = [...q.options].sort(() => Math.random() - 0.5).slice(0, n);
    } else {
      a[q.id] = [q.options[Math.floor(Math.random() * q.options.length)]];
    }
  }
  return a;
}

function rawFor(dimensions, role) {
  let weightedSum = 0, totalWeight = 0;
  for (const [dim, weight] of Object.entries(role.weights)) {
    if (weight > 0) {
      weightedSum += (dimensions[dim] || 0) * weight;
      totalWeight += weight * 100;
    }
  }
  return totalWeight > 0 ? (weightedSum / totalWeight) * 100 : 0;
}

const samples = Object.fromEntries(Object.keys(ROLES).map(k => [k, []]));

for (let i = 0; i < N; i++) {
  const dims = calculateDimensions(flattenAnswers(randomAnswers()));
  for (const [id, role] of Object.entries(ROLES)) samples[id].push(rawFor(dims, role));
}

const calibration = {};
for (const [id, vals] of Object.entries(samples)) {
  const mean = vals.reduce((a, b) => a + b, 0) / vals.length;
  const sd = Math.sqrt(vals.reduce((s, v) => s + (v - mean) ** 2, 0) / vals.length) || 1;
  calibration[id] = { mean: +mean.toFixed(3), sd: +sd.toFixed(3) };
}

const out = `// ============================================================
// AUTO-GENERATED by scripts/calibrate.mjs — do not edit by hand.
// Regenerate after changing any role weights or questions:
//   node scripts/calibrate.mjs
//
// mean and sd of each role's raw fit score across ${N.toLocaleString()}
// simulated respondents. Used to judge each role against its own
// range so that no role dominates and none is buried.
// ============================================================

export const CALIBRATION = ${JSON.stringify(calibration, null, 2)};
`;

writeFileSync('netlify/lib/calibration.mjs', out);
console.log(`Calibrated ${Object.keys(calibration).length} roles across ${N.toLocaleString()} respondents.`);
for (const [id, c] of Object.entries(calibration)) {
  console.log(`  ${id} ${ROLES[id].name.padEnd(32)} mean ${String(c.mean).padStart(6)}  sd ${c.sd}`);
}
